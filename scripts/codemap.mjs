/** Writes docs/CODEMAP.md: every source file with its first doc-comment sentence (--check fails if the file is stale). */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { extname, resolve, dirname } from 'node:path';
import { ROOT, repoFiles } from './lib/util.mjs';

const DIRS = ['src/', 'src-tauri/src/', 'crates/', 'scripts/', 'tools/'];
const EXTS = new Set(['rs', 'ts', 'tsx', 'js', 'jsx', 'mjs', 'cjs', 'css', 'html']);
const OUT = 'docs/CODEMAP.md';
const MAX = 160;

function firstSentence(text) {
  const t = text.replace(/\s+/g, ' ').trim();
  if (!t) return '';
  const m = t.match(/^(.*?[.!?])(\s|$)/);
  const s = m ? m[1] : t;
  return s.length > MAX ? s.slice(0, MAX - 1).trimEnd() + '…' : s;
}

function rustDoc(lines) {
  for (const prefix of ['//!', '///']) {
    const block = [];
    for (const l of lines) {
      const t = l.trim();
      if (t.startsWith(prefix) && !t.startsWith(prefix + '/')) block.push(t.slice(3));
      else if (block.length) break;
    }
    if (block.length) return block.join(' ');
  }
  return '';
}

function jsDoc(lines) {
  let i = 0;
  while (i < lines.length && (lines[i].trim() === '' || lines[i].startsWith('#!'))) i++;
  const first = (lines[i] ?? '').trim();
  if (first.startsWith('/*')) {
    const parts = [];
    for (; i < lines.length; i++) {
      let l = lines[i].trim();
      const end = l.includes('*/');
      l = l.replace(/^\/\*+/, '').replace(/\*\/.*$/, '').replace(/^\*\s?/, '');
      if (l.trim()) parts.push(l.trim());
      if (end) break;
    }
    return parts.join(' ');
  }
  const parts = [];
  for (; i < lines.length; i++) {
    const l = lines[i].trim();
    if (!l.startsWith('//')) break;
    parts.push(l.replace(/^\/\/+!?\s?/, ''));
  }
  return parts.join(' ');
}

export function build() {
  const byDir = new Map();
  for (const f of repoFiles()) {
    if (!DIRS.some((d) => f.startsWith(d)) || !EXTS.has(extname(f).slice(1))) continue;
    const lines = readFileSync(resolve(ROOT, f), 'utf8').split('\n');
    const doc = firstSentence(extname(f) === '.rs' ? rustDoc(lines) : jsDoc(lines));
    const dir = dirname(f);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(`- ${f} — ${doc || '(no doc comment)'}`);
  }
  const out = ['# Code map', '', 'Generated by `node scripts/codemap.mjs` — do not edit by hand. First doc-comment sentence per source file.', ''];
  for (const dir of [...byDir.keys()].sort()) {
    out.push(`## ${dir}/`, '', ...byDir.get(dir), '');
  }
  return out.join('\n');
}

const text = build();
const path = resolve(ROOT, OUT);
if (process.argv.includes('--check')) {
  const cur = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (cur !== text) {
    console.error(`${OUT} is out of date — run: node scripts/codemap.mjs`);
    process.exit(1);
  }
  console.log('codemap: up to date');
} else {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== text) writeFileSync(path, text);
  console.log(`codemap: wrote ${OUT}`);
}
